// 宿主标记不能当聊天内容入库
import { stripHostNoise, inboundBody, looksMemorable } from '../lib/prefilter.js';

let fail = 0;
const ok = (cond, label, extra = '') => {
  console.log(`${cond ? 'PASS' : 'FAIL'}  ${label}${extra ? '  ' + extra : ''}`);
  if (!cond) fail++;
};

const mixed =
  '怎么个事\nTime sampled while preparing turn 3, step 1: 2026-11-08T21:34:40+08:00[Asia/Singapore]\nBrowser time zone for this request: Asia/Singapore. Interpret otherwise-unqualified dates and times in this zone.\n[model changed: assistant turns above this point were generated by A; the session continues with B]';

ok(stripHostNoise(mixed) === '怎么个事', '真话 + 一堆宿主标记 → 只剩真话', JSON.stringify(stripHostNoise(mixed)));
ok(stripHostNoise('<system-reminder>hello</system-reminder>\n真正的内容') === '真正的内容', 'system-reminder 整块被去掉');

// 整条都是标记 → 判为不可用，不入库
const onlyMarks = inboundBody('Time sampled while preparing turn 3, step 1: 2026-11-08T21:34:40+08:00');
ok(onlyMarks.usable === false, '纯标记消息不入库', onlyMarks.reason);

// 真话 + 标记 → 可用，且正文干净
const b = inboundBody('怎么个事\n[model changed: x]');
ok(b.usable === true && b.body === '怎么个事', '混着标记的真话仍然入库且干净', JSON.stringify(b.body));

// 预筛也不该在这种内容上触发
ok(looksMemorable(stripHostNoise(mixed), { minChars: 4 }) === false, '净化后的短句不触发抽取（没有第一人称线索）');

console.log(fail === 0 ? '\n全部通过' : `\n${fail} 项失败`);
process.exit(fail === 0 ? 0 : 1);
